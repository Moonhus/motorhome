function listingImages(stock: string, count: number) {
  const gallery = Array.from(
    { length: count },
    (_, index) => `/images/listings/${stock}/${String(index + 1).padStart(2, "0")}.jpg`,
  );
  return { image: gallery[0], gallery };
}

/** 30% off the previous drive-away figure, rounded to the nearest $10. */
export function driveAway(listedPrice: number) {
  return Math.round((listedPrice * 0.7) / 10) * 10;
}

/** 25% off the listed drive-away figure, rounded to the nearest $10. */
export function driveAway25(listedPrice: number) {
  return Math.round((listedPrice * 0.75) / 10) * 10;
}

